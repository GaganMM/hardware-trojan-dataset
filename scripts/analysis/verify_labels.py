import json
import logging
import argparse
from pathlib import Path
import pandas as pd
import requests
import yaml
from tqdm import tqdm

from scripts.dataset.config import DatasetConfig

logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")
logger = logging.getLogger("LLMVerifier")

class LLMVerifier:
    def __init__(self, config: DatasetConfig, verify_model: str = "deepseek-coder:1.3b", target_source: str = "Local LLM Analysis"):
        self.config = config
        self.verify_model = verify_model
        self.target_source = target_source
        self.ollama_url = "http://localhost:11434/api/generate"
        self.generated_dir = self.config.knowledge / "generated"
        
    def prompt_llm(self, code_content: str) -> dict:
        prompt = f"""You are an expert hardware security researcher analyzing Verilog RTL for Hardware Trojans.
Examine the following Verilog code. Does it contain any malicious hardware trojan triggers (like timebombs, specific sequence counters, or cheat codes) or payloads (like leaking secrets, disabling security, or denial of service)?

Return ONLY a JSON object in the following format, with no additional text or markdown formatting:
{{
    "label": "Trojan" or "Clean",
    "confidence": <float between 0.0 and 1.0>,
    "reasoning": "<brief 1-2 sentence explanation of what you found or why it is clean>"
}}

Verilog Code:
{code_content[:6000]}
"""
        
        payload = {
            "model": self.verify_model,
            "prompt": prompt,
            "stream": False,
            "format": "json",
            "options": {
                "temperature": 0.1
            }
        }
        
        try:
            response = requests.post(self.ollama_url, json=payload, timeout=600)
            response.raise_for_status()
            result_text = response.json().get("response", "{}")
            return json.loads(result_text)
        except Exception as e:
            logger.error(f"LLM API Error: {e}")
            return None

    def run_verification(self, limit: int = None):
        # 1. Find all YAMLs generated by the target source
        target_yamls = []
        for yf in self.generated_dir.glob("*.yaml"):
            try:
                with open(yf, 'r', encoding='utf-8') as f:
                    data = yaml.safe_load(f) or {}
                    lbl_data = data.get("binary_label", {})
                    if lbl_data.get("source") == self.target_source:
                        target_yamls.append((yf.stem, lbl_data.get("value")))
            except Exception:
                continue
                
        logger.info(f"Found {len(target_yamls)} repositories labeled by {self.target_source}")
        
        if limit:
            target_yamls = target_yamls[:limit]
            
        # 2. Get files for these repositories from the manifest
        manifest_path = self.config.metadata / "manifest.csv"
        if not manifest_path.exists():
            logger.error("manifest.csv not found!")
            return
            
        df = pd.read_csv(manifest_path)
        
        results = []
        agreements = 0
        disagreements = 0
        
        for repo_name, original_label in tqdm(target_yamls, desc="Verifying Labels"):
            repo_files = df[df['repository'] == repo_name]['absolute_path'].tolist()
            if not repo_files:
                continue
                
            # Verify using the first file of the repo
            f = repo_files[0]
            try:
                p = self.config.root / f if not Path(f).is_absolute() else Path(f)
                content = p.read_text(errors='ignore')
            except Exception:
                continue
                
            if not content.strip():
                continue
                
            llm_result = self.prompt_llm(content)
            if llm_result:
                verified_label = llm_result.get("label", "Unknown")
                
                results.append({
                    "repository": repo_name,
                    "qwen_label": original_label,
                    "deepseek_label": verified_label,
                    "deepseek_confidence": llm_result.get("confidence", 0),
                    "deepseek_reasoning": llm_result.get("reasoning", "")
                })
                
                if verified_label == original_label:
                    agreements += 1
                else:
                    disagreements += 1
                    logger.info(f"DISAGREEMENT on {repo_name}: Qwen={original_label} vs DeepSeek={verified_label}")

        # 3. Save results
        out_path = self.config.metadata / "verification_results.csv"
        pd.DataFrame(results).to_csv(out_path, index=False)
        
        logger.info("======================================================")
        logger.info(f"Verification Complete!")
        logger.info(f"Total Evaluated: {len(results)}")
        logger.info(f"Agreements: {agreements}")
        logger.info(f"Disagreements: {disagreements}")
        if len(results) > 0:
            logger.info(f"Agreement Rate: {(agreements/len(results))*100:.2f}%")
        logger.info(f"Results saved to {out_path}")

def main():
    parser = argparse.ArgumentParser(description="Verify Qwen labels with DeepSeek")
    parser.add_argument("--model", type=str, default="deepseek-coder:1.3b", help="Model to use for verification")
    parser.add_argument("--target", type=str, default="Local LLM Analysis", help="Source of labels to verify")
    parser.add_argument("--limit", type=int, default=100, help="Number of repositories to verify")
    args = parser.parse_args()

    config = DatasetConfig.from_project_root(Path("."))
    verifier = LLMVerifier(config, verify_model=args.model, target_source=args.target)
    verifier.run_verification(limit=args.limit)

if __name__ == "__main__":
    main()
